import { Niivue } from "@niivue/niivue";
import { apiFetchMultipart } from "@/store/api";

export const uploadMaskToBackend = async (nvRef: React.RefObject<Niivue | null>, labelUrl: string, datasetName: string) => {
    const nv = nvRef;
    if (!nv) return;

    try {
        console.log("labelUrl", labelUrl);
        const label_path = labelUrl.split("label?label_path=")[1];

        // 1. Get the compressed mask as a Blob (using the interceptor below)
        // @ts-ignore
        const maskBlob = await getNiivueMaskBlob(nv, 'segmentation.nii.gz');

        // 2. Prepare the FormData for your backend
        const formData = new FormData();
        formData.append('file', maskBlob, 'segmentation.nii.gz');
        if (label_path) formData.append('label_path', label_path);
        if (datasetName) formData.append('dataset_name', datasetName);

        // 3. Send it off!
        const responseData = await apiFetchMultipart('/annotations/upload_mask', formData);
        console.log('Mask successfully uploaded!', responseData);

    } catch (error) {
        console.error('Error extracting or uploading mask:', error);
    }
};

/**
 * Intercepts NiiVue's forced download to return a Blob instead.
 */
export const getNiivueMaskBlob = (nvInstance: Niivue, filename: string): Promise<Blob> => {
    return new Promise((resolve, reject) => {
        // Save the browser's original click behavior
        const originalClick = HTMLAnchorElement.prototype.click;

        // Set a safety timeout just in case NiiVue fails silently (e.g., if no drawing exists)
        const timeout = setTimeout(() => {
            HTMLAnchorElement.prototype.click = originalClick;
            reject(new Error("Timeout generating mask blob. Make sure a drawing layer exists."));
        }, 5000);

        // Override the click method temporarily
        HTMLAnchorElement.prototype.click = function () {
            clearTimeout(timeout);
            const fileUrl = this.href; // This is the blob: URL generated by NiiVue

            // Immediately restore normal click behavior!
            HTMLAnchorElement.prototype.click = originalClick;

            // Fetch the generated object URL to extract the raw Blob
            fetch(fileUrl)
                .then((res) => res.blob())
                .then((blob) => {
                    URL.revokeObjectURL(fileUrl); // Clean up memory to avoid leaks
                    resolve(blob);
                })
                .catch(reject);
        };

        try {
            // Trigger NiiVue's generation. 
            // Note: Because the filename ends in .gz, NiiVue will automatically compress it!
            // @ts-ignore
            nvInstance.saveImage({ filename, isSaveDrawing: true });
        } catch (err) {
            clearTimeout(timeout);
            HTMLAnchorElement.prototype.click = originalClick;
            reject(err);
        }
    });
};